// "Filled" icons render with a solid fill and no stroke — used for the
// Test Connection screen's passed indicator (a filled green circle,
// design handoff §5) in addition to the base set's play/pause glyphs.
const FILLED = new Set(["play", "pause", "circle"]);

export type IconName = keyof typeof PATHS;

export interface IconProps {
  name: IconName;
  size?: number;
  color?: string;
}

// Ported from design-system/components-reference/core/icon/Icon.jsx — one
// React component holding the whole inline-SVG sprite (Feather-style,
// stroke-width 2, 24x24), never generated dynamically.
export function Icon({ name, size = 18, color = "currentColor" }: IconProps) {
  const inner = PATHS[name];
  if (!inner) return null;
  const filled = FILLED.has(name);
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={filled ? color : "none"}
      stroke={filled ? "none" : color}
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      {inner}
    </svg>
  );
}
